package lol.zyrex.utils.display.theme;

import java.awt.Color;

public final class UITheme {
    private UITheme() {}

    public static Color mutedText() { return new Color(150, 150, 150); }
    public static Color textColor() { return new Color(200, 200, 200); }
    public static Color outlineColor() { return new Color(100, 100, 100); }
    public static Color buttonColor() { return new Color(70, 70, 75); }
    public static Color gradientColor() { return new Color(55, 55, 60); }


}
